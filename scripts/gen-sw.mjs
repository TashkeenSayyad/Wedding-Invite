// Writes docs/sw.js after the Vite build, with the built file list baked in.
//
// Two reasons this exists. Guests open the invitation at the hall, where the signal is whatever
// it is; and guests travelling up from Karachi open it on the road. Once the page has been seen
// once it should open again with no network at all — and, being installable, sit on a home screen
// instead of being lost in a WhatsApp thread.
//
// Everything the build emits is precached except the 2.1 MB print card, which is far too heavy to
// push onto a phone up front — that one is cached the first time a guest opens or saves it.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const docs = resolve(root, "docs");

const RUNTIME_ONLY = [
  "assets/card-print.png",  // 2.1 MB; cached the first time a guest opens or saves it
  "assets/og-card.jpg",    // only ever fetched by link-preview crawlers, never by the page
];

// Audio is left to the browser entirely: not precached (a song is several MB to push onto a phone
// that may never unmute it) and not served from the cache, because a media element asks for byte
// ranges and Safari will not play a whole-file answer to a range request.
const AUDIO = /\.(mp3|m4a|aac|ogg|opus|wav)$/i;

const walk = (dir) => readdirSync(dir).flatMap((name) => {
  const full = join(dir, name);
  return statSync(full).isDirectory() ? walk(full) : [relative(docs, full).split("\\").join("/")];
});

const files = walk(docs)
  .filter((f) => f !== "sw.js" && !RUNTIME_ONLY.includes(f) && !AUDIO.test(f))
  .sort();

// The cache name changes whenever any built file does, which is what evicts the previous version.
// It hashes what is *in* the files, not only their names: index.html keeps its name from build to
// build, so a change to it alone used to leave the cache name — and the stale page — where it was.
const h = createHash("sha256");
for (const f of files) h.update(f).update("\0").update(readFileSync(resolve(docs, f))).update("\0");
const version = h.digest("hex").slice(0, 12);
const precache = ["./", ...files.map((f) => "./" + f)];

const sw = `// Generated by scripts/gen-sw.mjs — do not edit by hand.
const CACHE = "ta-${version}";
const PRECACHE = ${JSON.stringify(precache, null, 2)};

// GitHub Pages lets a browser reuse a copy of any file for ten minutes. A precache filled from that
// copy stored the previous build's index.html under the new cache — a page that asks for scripts
// the server no longer has, which rendered a white screen. Every precache fetch skips the browser's
// copy and goes to the server.
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE)
    .then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: "reload" }))))
    .then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (e) => {
  const { request } = e;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // the song streams straight from the network — see AUDIO in scripts/gen-sw.mjs
  if (request.destination === "audio" || request.headers.has("range")) return;

  // Navigations go to the network first, revalidated rather than taken from the browser's ten-
  // minute copy, so the page is always the one the current build's files belong to. The cached
  // shell is the fallback for no signal, or for a signal so weak the server has not answered in
  // three seconds — a personalised ?to= link still opens at the hall.
  if (request.mode === "navigate") {
    e.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const shell = await cache.match("./", { ignoreSearch: true });
      const fresh = fetch(request.url, { cache: "no-cache", credentials: "same-origin" }).then((r) => {
        if (r.ok && !r.redirected) cache.put("./", r.clone());
        return r;
      });
      if (!shell) return fresh;
      const slow = new Promise((ok) => setTimeout(() => ok(shell), 3000));
      return Promise.race([fresh.catch(() => shell), slow]);
    })());
    return;
  }

  // Everything else: cache first (the build's filenames are content-hashed), network on a miss,
  // and whatever comes back gets kept — that is how the print card lands in the cache.
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(request, { ignoreSearch: false });
    if (hit) return hit;
    try {
      const res = await fetch(request);
      if (res.ok && res.type === "basic") cache.put(request, res.clone());
      return res;
    } catch (err) {
      const any = await cache.match(request, { ignoreSearch: true });
      if (any) return any;
      throw err;
    }
  })());
});
`;

writeFileSync(resolve(docs, "sw.js"), sw);
const bytes = precache.slice(1).reduce((n, f) => n + statSync(resolve(docs, f.slice(2))).size, 0);
console.log(`sw.js  cache ta-${version}  ${precache.length} entries  ${(bytes / 1024).toFixed(0)} KB precached`);
